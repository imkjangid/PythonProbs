# Arithmetic Behavior
x = 5
y = 6

print("Addition (+):", x + y) # Output: 11
print("Standard Division (/) always returns float:", x / y) # Output: 0.8333333333333334
print("Floor Division (//) truncates down:", x // y) # Output: 0
print("Modulo (%) returns remainder:", x % y) # Output: 5
print("Exponentiation (**):", x ** 3) # Output: 125